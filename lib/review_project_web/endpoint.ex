defmodule ReviewProjectWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :review_project

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_review_project_key",
    signing_salt: "tUuLBbjG",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  socket "/room-socket", ReviewProjectWeb.RoomSocket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: false

  # Phase 0 spike: raw membrane_webrtc_plugin signaling over a plain Phoenix
  # socket (no LiveView), used by the Hologram WebRTC integration spike so the
  # Hologram-owned browser PeerConnection can negotiate with Membrane Source/Sink.
  socket "/signaling", Membrane.WebRTC.PhoenixSignaling.Socket,
    websocket: true,
    longpoll: false

  if Application.compile_env(:review_project, :youtube_sync_spike, false) do
    socket "/dev/spikes/room-access-socket", ReviewProjectWeb.RoomSpikeSocket,
      websocket: [connect_info: [session: @session_options]],
      longpoll: false

    socket "/dev/spikes/youtube-sync-socket", ReviewProjectWeb.YouTubeSyncSocket,
      websocket: true,
      longpoll: false
  end

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :review_project,
    gzip: not code_reloading?,
    only: ReviewProjectWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  if Mix.env() == :dev do
    plug Tidewave, toolbar: false
  end

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :review_project
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug :hologram_websocket_before_telemetry
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug :fetch_remembered_user_token
  plug Hologram.Router
  plug ReviewProjectWeb.Router

  defp hologram_websocket_before_telemetry(
         %Plug.Conn{request_path: "/hologram/websocket"} = conn,
         _opts
       ) do
    Hologram.Router.call(conn, [])
  end

  defp hologram_websocket_before_telemetry(conn, _opts), do: conn

  # Hologram.Router serves pages before the router's :browser pipeline.
  defp fetch_remembered_user_token(conn, opts),
    do: ReviewProjectWeb.UserAuth.fetch_remembered_user_token(conn, opts)
end
